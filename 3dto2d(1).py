gamma_M101 = 1.0 + C_RVT * np.sin(inclination_M101)

print(f"Zielausrichtung gamma_RVT(90°)      = {gamma_90:.3f}")
print(f"gamma_RVT(NGC 891, 85°)             = {gamma_891:.3f}")
print(f"gamma_RVT(M101, 18°)                = {gamma_M101:.3f}")

