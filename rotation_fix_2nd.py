    green_dots_plot.set_data(green_dots_x, green_dots_y); green_dots_plot.set_3d_properties(green_dots_z)

    return [equator_plot, obs_point, obs_dotted_line, horiz_line, yellow_line, eq_obs_line, blue_trace_plot, green_dots_plot, axis_plot] + green_lines_plots

