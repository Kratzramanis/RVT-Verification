import matplotlib.pyplot as plt
import numpy as np
from matplotlib.animation import FuncAnimation
from IPython.display import HTML

# Parameter
r = 1.0
tilt_deg = 23.5
tilt_rad = np.deg2rad(tilt_deg)
lat_45_rad = np.deg2rad(45)
fps = 16
duration_s = 8
total_frames = fps * duration_s

fig = plt.figure(figsize=(10, 10))
ax = fig.add_subplot(111, projection='3d')
fig.patch.set_facecolor('#0d1117')
ax.set_facecolor('#161b22')

# Basis-Daten für die Erde
u_vec = np.linspace(0, 2*np.pi, 30)
v_vec = np.linspace(0, np.pi, 20)
U, V = np.meshgrid(u_vec, v_vec)
x_base = r * np.cos(U) * np.sin(V)
y_base = r * np.sin(U) * np.sin(V)
z_base = r * np.cos(V)

def apply_tilt(x, y, z):
    xt = x * np.cos(tilt_rad) + z * np.sin(tilt_rad)
    yt = y
    zt = -x * np.sin(tilt_rad) + z * np.cos(tilt_rad)
    return xt, yt, zt

def rotate_around_axis(x, y, z, angle):
    xr = x * np.cos(angle) - y * np.sin(angle)
    yr = x * np.sin(angle) + y * np.cos(angle)
    zr = z
    return xr, yr, zr

# Statische Achse
axis_len = 1.8
north = np.array([axis_len * np.sin(tilt_rad), 0, axis_len * np.cos(tilt_rad)])
south = -north
ax.plot([south[0], north[0]], [0, 0], [south[2], north[2]], color='white', linewidth=3)

# Plots initialisieren
wireframe = [ax.plot_wireframe(*apply_tilt(x_base, y_base, z_base), color='#58a6ff', alpha=0.1, linewidth=0.5)]
phi = np.linspace(0, 2*np.pi, 100)
eq_x_b, eq_y_b, eq_z_b = r * np.cos(phi), r * np.sin(phi), np.zeros_like(phi)
equator_plot, = ax.plot(*apply_tilt(eq_x_b, eq_y_b, eq_z_b), color='#ff7b72', linewidth=2.5)

# Beobachter und Linien
obs_point, = ax.plot([], [], [], 'o', color='#1f6feb', markersize=8)
obs_dotted_line, = ax.plot([], [], [], color='#1f6feb', linestyle=':', linewidth=2)
horiz_line, = ax.plot([], [], [], color='#1f6feb', linewidth=2)
yellow_line, = ax.plot([], [], [], color='#ffeb3b', linewidth=3)
eq_obs_line, = ax.plot([], [], [], color='#ff7b72', linewidth=2)

# Grüne Viertel-Markierungen (Punkte und Linien)
green_dots_x, green_dots_y, green_dots_z = [], [], []
green_dots_plot, = ax.plot([], [], [], 'o', color='#2ea043', markersize=8, alpha=0.8, linestyle='None')
green_lines_plots = []
orange_fixed_points = []

# Traces
blue_trace_x, blue_trace_y, blue_trace_z = [], [], []
yellow_trace1_x, yellow_trace1_y, yellow_trace1_z = [], [], []
yellow_trace2_x, yellow_trace2_y, yellow_trace2_z = [], [], []
eq_trace_x, eq_trace_y, eq_trace_z = [], [], []

blue_trace_plot, = ax.plot([], [], [], color='#1f6feb', alpha=0.6, linewidth=1.5)
yellow_trace1_plot, = ax.plot([], [], [], color='#ffeb3b', alpha=0.6, linewidth=1.5)
yellow_trace2_plot, = ax.plot([], [], [], color='#ffeb3b', alpha=0.6, linewidth=1.5)
eq_trace_plot, = ax.plot([], [], [], color='#ff7b72', alpha=0.6, linewidth=1.5)

def update(frame):
    angle = (frame / total_frames) * 4 * np.pi

    if frame == 0 or frame == total_frames // 2:
        for t in [blue_trace_x, blue_trace_y, blue_trace_z,
                  yellow_trace1_x, yellow_trace1_y, yellow_trace1_z,
                  yellow_trace2_x, yellow_trace2_y, yellow_trace2_z,
                  eq_trace_x, eq_trace_y, eq_trace_z,
                  green_dots_x, green_dots_y, green_dots_z]: t.clear()
        for ln in green_lines_plots:
            try: ln.remove()
            except: pass
        for pt in orange_fixed_points:
            try: pt.remove()
            except: pass
        green_lines_plots.clear()
        orange_fixed_points.clear()

    xr, yr, zr = rotate_around_axis(x_base, y_base, z_base, angle)
    xt, yt, zt = apply_tilt(xr, yr, zr)
    wireframe[0].remove()
    wireframe[0] = ax.plot_wireframe(xt, yt, zt, color='#58a6ff', alpha=0.1, linewidth=0.5)

    exr, eyr, ezr = rotate_around_axis(eq_x_b, eq_y_b, eq_z_b, angle)
    ext, eyt, ezt = apply_tilt(exr, eyr, ezr)
    equator_plot.set_data(ext, eyt); equator_plot.set_3d_properties(ezt)

    l = 0.8
    center = np.array([0, 0, 0])
    b45 = np.array([r * np.sin(-lat_45_rad), 0, r * np.cos(-lat_45_rad)])

    y45_ang = -lat_45_rad - np.pi/2
    y45_end1 = b45 + np.array([l * np.sin(y45_ang), 0, l * np.cos(y45_ang)])
    y45_end2 = b45 - np.array([l * np.sin(y45_ang), 0, l * np.cos(y45_ang)])

    pts_loc = [center, b45, y45_end1, y45_end2]
    pts_final = [apply_tilt(*rotate_around_axis(p[0], p[1], p[2], angle)) for p in pts_loc]
    c_rot, obs, yel1, yel2 = pts_final

    h45_loc = b45 + np.array([-l, 0, 0])
    hor = apply_tilt(*rotate_around_axis(h45_loc[0], h45_loc[1], h45_loc[2], angle))

    obs_point.set_data([obs[0]], [obs[1]]); obs_point.set_3d_properties([obs[2]])
    obs_dotted_line.set_data([c_rot[0], obs[0]], [c_rot[1], obs[1]]); obs_dotted_line.set_3d_properties([c_rot[2], obs[2]])
    horiz_line.set_data([obs[0], hor[0]], [obs[1], hor[1]]); horiz_line.set_3d_properties([obs[2], hor[2]])
    yellow_line.set_data([yel1[0], yel2[0]], [yel1[1], yel2[1]]); yellow_line.set_3d_properties([yel1[2], yel2[2]])

    beq_loc = np.array([-r, 0, 0])
    heq_loc = beq_loc + np.array([-l, 0, 0])
    eq_b_final = apply_tilt(*rotate_around_axis(beq_loc[0], beq_loc[1], beq_loc[2], angle))
    eq_h_final = apply_tilt(*rotate_around_axis(heq_loc[0], heq_loc[1], heq_loc[2], angle))
    eq_obs_line.set_data([eq_b_final[0], eq_h_final[0]], [eq_b_final[1], eq_h_final[1]]); eq_obs_line.set_3d_properties([eq_b_final[2], eq_h_final[2]])

    blue_trace_x.append(hor[0]); blue_trace_y.append(hor[1]); blue_trace_z.append(hor[2])
    yellow_trace1_x.append(yel1[0]); yellow_trace1_y.append(yel1[1]); yellow_trace1_z.append(yel1[2])
    yellow_trace2_x.append(yel2[0]); yellow_trace2_y.append(yel2[1]); yellow_trace2_z.append(yel2[2])
    eq_trace_x.append(eq_h_final[0]); eq_trace_y.append(eq_h_final[1]); eq_trace_z.append(eq_h_final[2])

    quarter_step = total_frames / 8
    if frame % int(quarter_step) == 0:
        green_dots_x.append(hor[0]); green_dots_y.append(hor[1]); green_dots_z.append(hor[2])
        obs_arr = np.array(obs)
        hor_arr = np.array(hor)
        direction_vector = hor_arr - obs_arr
        g_line_end = hor_arr + 2.0 * direction_vector
        new_ln, = ax.plot([hor_arr[0], g_line_end[0]], [hor_arr[1], g_line_end[1]], [hor_arr[2], g_line_end[2]], color='#2ea043', linewidth=2, alpha=0.8)
        green_lines_plots.append(new_ln)
        # Oranger Punkt am Endpunkt der grünen Linie
        pt = ax.scatter([g_line_end[0]], [g_line_end[1]], [g_line_end[2]], color='#ffa657', s=150, edgecolors='white', linewidth=2, zorder=50)
        orange_fixed_points.append(pt)

    blue_trace_plot.set_data(blue_trace_x, blue_trace_y); blue_trace_plot.set_3d_properties(blue_trace_z)
    yellow_trace1_plot.set_data(yellow_trace1_x, yellow_trace1_y); yellow_trace1_plot.set_3d_properties(yellow_trace1_z)
    yellow_trace2_plot.set_data(yellow_trace2_x, yellow_trace2_y); yellow_trace2_plot.set_3d_properties(yellow_trace2_z)
    eq_trace_plot.set_data(eq_trace_x, eq_trace_y); eq_trace_plot.set_3d_properties(eq_trace_z)
    green_dots_plot.set_data(green_dots_x, green_dots_y); green_dots_plot.set_3d_properties(green_dots_z)

    return [equator_plot, obs_point, obs_dotted_line, horiz_line, yellow_line, eq_obs_line, blue_trace_plot, green_dots_plot] + green_lines_plots

ax.view_init(elev=5, azim=-90)
ax.set_axis_off()
ax.set_xlim(-2.5, 2.5); ax.set_ylim(-2.5, 2.5); ax.set_zlim(-2.5, 2.5)
ani = FuncAnimation(fig, update, frames=total_frames, interval=1000/fps, blit=False)
plt.close()
HTML(ani.to_jshtml())

