blue_trace2_x, blue_trace2_y, blue_trace2_z = [], [], []
eq_trace2_x, eq_trace2_y, eq_trace2_z = [], [], []
blue_trace2_plot, = ax.plot([], [], [], color='#79c0ff', alpha=0.3, linewidth=4.0)
eq_trace2_plot, = ax.plot([], [], [], color='#ffa657', alpha=0.3, linewidth=4.0)

def calculate_z_for_frame(f):
    """ Hilfsfunktion zur exakten Berechnung der Punkt 1 3D-Z-Höhe für jeden beliebigen Frame """
    angle = (f / total_frames) * 4 * np.pi
    angle_global = angle / np.cos(lat_45_rad)

    # Koordinaten-Vektoren für Punkt 1 (yel1)
    b45 = np.array([r * np.sin(-lat_45_rad), 0, r * np.cos(-lat_45_rad)])
    y45_ang = -lat_45_rad - np.pi/2
    tangent_direction = np.array([np.sin(y45_ang), 0, np.cos(y45_ang)])
    y45_end1 = b45 + 0.8 * tangent_direction

    # Tilted & Rotated Point 1 (yel1_f)
    pts_tilted = apply_tilt(*rotate_around_axis(y45_end1[0], y45_end1[1], y45_end1[2], angle))
    obs_tilted = apply_tilt(*rotate_around_axis(b45[0], b45[1], b45[2], angle))

    obs_f = rotate_global(obs_tilted[0], obs_tilted[1], obs_tilted[2], angle_global)
    yel1_f = rotate_global(pts_tilted[0], pts_tilted[1], pts_tilted[2], angle_global)

    # Horiz-Punkt für die äußere Linie (G_LINE_END)
    h45_loc = b45 + np.array([-0.8, 0, 0])
    hor_tilted = apply_tilt(*rotate_around_axis(h45_loc[0], h45_loc[1], h45_loc[2], angle))
    hor_f = rotate_global(hor_tilted[0], hor_tilted[1], hor_tilted[2], angle_global)

    tangent_vector = np.array(yel1_f) - np.array(obs_f)
    unit_tangent = tangent_vector / np.linalg.norm(tangent_vector) if np.linalg.norm(tangent_vector) > 0 else np.array([0, 1, 0])

    space_hor_arr = np.array(hor_f)
    g_line_end = space_hor_arr + 2.0 * (space_hor_arr - np.array(obs_f))
    return g_line_end[2]

# MATHEMATISCHE ANALYSE DURCHFÜHREN UND PER PRINTSCRIPT AUSGEBEN (Kein Text im Plot!)
for f in frames_to_capture:
    captured_z_values[f] = calculate_z_for_frame(f)

