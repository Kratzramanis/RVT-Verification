x_base = r * np.cos(U) * np.sin(V)
y_base = r * np.sin(U) * np.sin(V)
z_base = r * np.cos(V)

def apply_tilt(x, y, z):
    xt = x * np.cos(tilt_rad) + z * np.sin(tilt_rad)
    yt = y
    zt = -x * np.sin(tilt_rad) + z * np.cos(tilt_rad)
    return xt, yt, zt

def rotate_around_axis(x, y, z, angle):
    xr = x * np.cos(angle) - y * np.sin(angle)
    yr = x * np.sin(angle) + y * np.cos(angle)
    zr = z
    return xr, yr, zr

def rotate_global(x, y, z, g_angle):
    xg = x * np.cos(g_angle) - y * np.sin(g_angle)
    yg = x * np.sin(g_angle) + y * np.cos(g_angle)
    zg = z
    return xg, yg, zg

# Statische Achsen-Basisvektoren
axis_len = 1.8
north_base = np.array([axis_len * np.sin(tilt_rad), 0, axis_len * np.cos(tilt_rad)])
south_base = -north_base

